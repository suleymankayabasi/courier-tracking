create table stores (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    lat double precision not null,
    lng double precision not null,
    constraint uk_stores_name unique (name)
);

create table courier_states (
    courier_id varchar(64) primary key,
    last_lat double precision not null,
    last_lng double precision not null,
    last_time timestamp with time zone not null,
    total_distance_meters double precision not null,
    version bigint
);

create table courier_locations (
    id bigint generated by default as identity primary key,
    courier_id varchar(64) not null,
    lat double precision not null,
    lng double precision not null,
    event_time timestamp with time zone not null
);

create index idx_courier_location_courier_time on courier_locations (courier_id, event_time);

create table store_entrances (
    id bigint generated by default as identity primary key,
    courier_id varchar(64) not null,
    store_id bigint not null,
    entrance_time timestamp with time zone not null,
    constraint fk_store_entrances_store foreign key (store_id) references stores (id)
);

create index idx_store_entrance_courier_store_time on store_entrances (courier_id, store_id, entrance_time);
